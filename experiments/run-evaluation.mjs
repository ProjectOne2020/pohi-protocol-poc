/**
 * @file run-evaluation.mjs
 * @package experiments/
 *
 * Runs the PoHI adversarial evaluation and reports the detection metrics of whitepaper
 * Ch.10 Section 10.3.
 *
 * Usage:
 *   node experiments/run-evaluation.mjs --human data/human-corpus.json
 *   node experiments/run-evaluation.mjs --harness          (pipeline smoke test only)
 *
 * Options:
 *   --human <path>     Corpus of sessions captured from consenting participants.
 *   --harness          Use generated data to exercise the pipeline. NOT empirical evidence.
 *   --calibration <k>  escrow | merchant | gaming | forum   (default: escrow)
 *   --sessions <n>     Adversarial sessions generated per adversary (default: matches human n).
 *   --seed <n>         Master seed for reproducibility (default: 20260729).
 *   --out <path>       Write the full result bundle as JSON.
 */

import { writeFileSync } from 'node:fs';
import { loadCorpus, generateHarnessCorpus, PROVENANCE } from './src/dataset.mjs';
import { CALIBRATIONS, scoreCorpus } from './src/scoring.mjs';
import { ADVERSARIES, fitCorpusStatistics, generateAdversarialCorpus } from './src/adversaries.mjs';
import { evaluate } from './src/metrics.mjs';

// ---------------------------------------------------------------------------------------

function parseArguments(argv) {
  const options = {
    human: null,
    harness: false,
    calibration: 'escrow',
    sessions: null,
    seed: 20260729,
    out: null,
  };
  for (let i = 0; i < argv.length; i++) {
    const flag = argv[i];
    if (flag === '--harness') options.harness = true;
    else if (flag === '--human') options.human = argv[++i];
    else if (flag === '--calibration') options.calibration = argv[++i];
    else if (flag === '--sessions') options.sessions = Number(argv[++i]);
    else if (flag === '--seed') options.seed = Number(argv[++i]);
    else if (flag === '--out') options.out = argv[++i];
  }
  return options;
}

const options = parseArguments(process.argv.slice(2));

if (!options.human && !options.harness) {
  process.stderr.write(
    'Provide a participant corpus with --human <path>, or --harness to smoke-test the pipeline.\n' +
      'See experiments/README.md for the collection protocol.\n'
  );
  process.exit(2);
}

const calibration = CALIBRATIONS[options.calibration];
if (!calibration) {
  process.stderr.write(`Unknown calibration "${options.calibration}".\n`);
  process.exit(2);
}

const humanCorpus = options.human ? loadCorpus(options.human) : generateHarnessCorpus({ seed: options.seed });
const isEmpirical = humanCorpus.provenance === PROVENANCE.HUMAN;
const adversarialSessionCount = options.sessions ?? humanCorpus.sessions.length;

// ---------------------------------------------------------------------------------------

const line = (char = '─') => char.repeat(78);
const pct = (x) => `${(x * 100).toFixed(1)}%`;

process.stdout.write(`\n${line('═')}\n`);
process.stdout.write('PoHI ADVERSARIAL EVALUATION\n');
process.stdout.write(`${line('═')}\n\n`);

if (!isEmpirical) {
  process.stdout.write(
    '  ┌──────────────────────────────────────────────────────────────────────────┐\n' +
      '  │  PIPELINE SMOKE TEST — NOT EMPIRICAL EVIDENCE                            │\n' +
      '  │                                                                          │\n' +
      '  │  The "human" corpus is generated by a statistical process, not captured  │\n' +
      '  │  from people. It exercises the code path only. Every number below is     │\n' +
      '  │  meaningless as a claim about real typists and must never be published,  │\n' +
      '  │  cited, or shown to a counterparty as a result.                          │\n' +
      '  └──────────────────────────────────────────────────────────────────────────┘\n\n'
  );
}

process.stdout.write(`Calibration      : ${calibration.label}\n`);
process.stdout.write(
  `Weights          : alpha=${calibration.alpha}  beta=${calibration.beta}  gamma=${calibration.gamma}\n`
);
process.stdout.write(`Threshold theta  : ${calibration.theta}\n`);
process.stdout.write(`Reference corpus : ${humanCorpus.source} (${humanCorpus.provenance})\n`);
process.stdout.write(`Sessions         : ${humanCorpus.sessions.length} reference, ${adversarialSessionCount} per adversary\n`);
process.stdout.write(`Master seed      : ${options.seed}\n\n`);

// ---------------------------------------------------------------------------------------

const statistics = fitCorpusStatistics(humanCorpus);
const referenceScores = scoreCorpus(humanCorpus, calibration);
const referenceValues = referenceScores.map((r) => r.score);
const acceptedReference = referenceScores.filter((r) => r.isValid).length;

process.stdout.write(`${line()}\nREFERENCE POPULATION\n${line()}\n`);
process.stdout.write(
  `  Accepted at theta=${calibration.theta}: ${acceptedReference}/${referenceScores.length} ` +
    `(${pct(acceptedReference / referenceScores.length)})\n`
);
process.stdout.write(
  `  Score  mean=${(referenceValues.reduce((a, c) => a + c, 0) / referenceValues.length).toFixed(4)} ` +
    `min=${Math.min(...referenceValues).toFixed(4)} max=${Math.max(...referenceValues).toFixed(4)}\n`
);
process.stdout.write(
  `  Fitted flight log-normal: mu=${statistics.flightLogMean.toFixed(3)} ` +
    `sigma=${statistics.flightLogSd.toFixed(3)} (from ${statistics.sampleSizes.flights} samples)\n\n`
);

// ---------------------------------------------------------------------------------------

const results = [];

for (const adversary of ADVERSARIES) {
  const corpus = generateAdversarialCorpus(adversary, {
    sessions: adversarialSessionCount,
    seed: options.seed + adversary.id.length,
    statistics,
    humanCorpus,
  });

  const scored = scoreCorpus(corpus, calibration);
  const values = scored.map((r) => r.score);
  const metrics = evaluate(referenceValues, values, calibration.theta, { seed: options.seed });

  results.push({ adversary: { id: adversary.id, label: adversary.label, threatVector: adversary.threatVector, knowledge: adversary.knowledge }, metrics });

  process.stdout.write(`${line()}\n${adversary.id}  ${adversary.label}\n${line()}\n`);
  process.stdout.write(`  Threat vector  : ${adversary.threatVector}\n`);
  process.stdout.write(`  Knowledge      : ${adversary.knowledge}\n`);
  process.stdout.write(
    `  Score          : mean=${metrics.adversarialScores.mean.toFixed(4)} ` +
      `median=${metrics.adversarialScores.median.toFixed(4)} max=${metrics.adversarialScores.max.toFixed(4)}\n`
  );
  process.stdout.write(
    `  FAR at theta   : ${pct(metrics.far)}  ` +
      `[95% CI ${pct(metrics.farInterval.lower)} – ${pct(metrics.farInterval.upper)}]\n`
  );
  process.stdout.write(`  AUC            : ${metrics.auc.toFixed(4)}  [95% CI ${metrics.aucInterval.lower.toFixed(4)} – ${metrics.aucInterval.upper.toFixed(4)}]\n`);
  process.stdout.write(`  EER            : ${pct(metrics.eer)} at theta=${metrics.eerThreshold.toFixed(4)}\n`);

  const verdict =
    metrics.far === 0
      ? 'REJECTED — no adversarial session reached the threshold'
      : metrics.far < 0.05
        ? 'LARGELY REJECTED — below 5% acceptance'
        : metrics.far < 0.5
          ? 'PARTIALLY EFFECTIVE — a substantial fraction passes'
          : 'DEFEATS THE PROTOCOL — the majority passes';
  process.stdout.write(`  Verdict        : ${verdict}\n\n`);
}

// ---------------------------------------------------------------------------------------

process.stdout.write(`${line('═')}\nSUMMARY\n${line('═')}\n\n`);
process.stdout.write(`  ${'Adversary'.padEnd(34)}${'FAR'.padStart(9)}${'AUC'.padStart(9)}${'EER'.padStart(9)}\n`);
process.stdout.write(`  ${line('-').slice(0, 61)}\n`);
for (const { adversary, metrics } of results) {
  process.stdout.write(
    `  ${adversary.label.padEnd(34)}${pct(metrics.far).padStart(9)}${metrics.auc.toFixed(3).padStart(9)}${pct(metrics.eer).padStart(9)}\n`
  );
}

const worst = results.reduce((a, b) => (b.metrics.far > a.metrics.far ? b : a));
process.stdout.write(
  `\n  Strongest adversary: ${worst.adversary.label} at FAR ${pct(worst.metrics.far)}.\n`
);
process.stdout.write(
  '  The protocol\'s practical security is bounded by this figure, not by the weakest adversary.\n'
);
process.stdout.write(
  `\n  Note: scores within +/-0.0122 of theta are indeterminate under the circuit\n` +
    '  implementation (PSP-0002). Sessions in that band may be classified differently\n' +
    '  by the reference engine and by the R1CS circuit.\n'
);

if (!isEmpirical) {
  process.stdout.write(
    '\n  REMINDER: this run used generated data. It demonstrates that the pipeline works;\n' +
      '  it demonstrates nothing about the protocol. Collect participant data and re-run.\n'
  );
}

if (options.out) {
  writeFileSync(
    options.out,
    `${JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        empirical: isEmpirical,
        calibration: { key: options.calibration, ...calibration },
        seed: options.seed,
        referenceCorpus: { source: humanCorpus.source, provenance: humanCorpus.provenance, sessions: humanCorpus.sessions.length },
        statistics,
        results,
      },
      null,
      2
    )}\n`
  );
  process.stdout.write(`\n  Full results written to ${options.out}\n`);
}

process.stdout.write('\n');
